use serde::{Deserialize, Serialize};

#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub enum ServiceTier {
    PersonalItem,
    StandardEconomy,
    PremiumEconomy,
    BusinessFirst,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct CarrierEnvelope {
    pub carrier_code: &'static str,
    pub carrier_name: &'static str,
    pub tier: ServiceTier,
    pub max_length_cm: f64,
    pub max_width_cm: f64,
    pub max_depth_cm: f64,
    pub max_weight_kg: Option<f64>,
    pub underseat_allowed: bool,
    pub verified_source: &'static str,
}

impl CarrierEnvelope {
    #[allow(clippy::too_many_arguments)]
    pub const fn new(
        carrier_code: &'static str,
        carrier_name: &'static str,
        tier: ServiceTier,
        max_length_cm: f64,
        max_width_cm: f64,
        max_depth_cm: f64,
        max_weight_kg: Option<f64>,
        underseat_allowed: bool,
        verified_source: &'static str,
    ) -> Self {
        Self {
            carrier_code,
            carrier_name,
            tier,
            max_length_cm,
            max_width_cm,
            max_depth_cm,
            max_weight_kg,
            underseat_allowed,
            verified_source,
        }
    }

    /// Evaluates if an item or bag exceeds this dimensional envelope
    pub fn fits(
        &self,
        length_cm: f64,
        width_cm: f64,
        depth_cm: f64,
        weight_kg: Option<f64>,
    ) -> bool {
        let dim_fit = length_cm <= self.max_length_cm
            && width_cm <= self.max_width_cm
            && depth_cm <= self.max_depth_cm;

        let weight_fit = match (self.max_weight_kg, weight_kg) {
            (Some(max_w), Some(w)) => w <= max_w,
            _ => true,
        };

        dim_fit && weight_fit
    }
}

